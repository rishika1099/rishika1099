// Run with node scripts/test-image-variants.cjs. All data stays in a disposable directory.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const sharp = require('sharp');
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8').replace(/(["'])@\//g, '$1' + path.join(__dirname, '../src/')), { compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: true, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const root = path.resolve(__dirname, '..');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'portfolio-image-tests-'));
process.chdir(temporary);
delete process.env.NETLIFY;
delete process.env.NETLIFY_BLOBS_CONTEXT;
(async () => {
  const { writePhoto, readThumbnail, readPhotoBytes, removePhoto } = require(path.join(root, 'src/lib/photos.ts'));
  const { writeFileKind, readDisplayFile, readFileKind, deleteFileKind } = require(path.join(root, 'src/lib/files.ts'));
  const make = color => sharp({ create: { width: 1600, height: 1200, channels: 3, background: color } }).jpeg().toBuffer();
  const red = await make('#e38698');
  const blue = await make('#637bc4');
  const tall = await sharp({ create: { width: 800, height: 1600, channels: 3, background: '#e38698' } }).jpeg().toBuffer();
  await writePhoto('tall.jpg', tall);
  assert.equal((await sharp(await readThumbnail('tall.jpg', 384)).metadata()).width, 384, 'portrait thumbnails need full responsive width');
  await writePhoto('sample.jpg', red);
  const thumb = await readThumbnail('sample.jpg', 384);
  assert.equal((await sharp(thumb).metadata()).width, 384);
  assert.deepEqual(await readPhotoBytes('sample.jpg'), red);
  const cached = path.join(temporary, 'src/content/image-variants/photos-v2/sample.jpg-384.webp');
  const before = fs.statSync(cached).mtimeMs;
  assert.deepEqual(await readThumbnail('sample.jpg', 384), thumb);
  assert.equal(fs.statSync(cached).mtimeMs, before, 'cache hit must not resize or rewrite');
  await writePhoto('sample.jpg', blue);
  assert.notDeepEqual(await readThumbnail('sample.jpg', 384), thumb);
  await removePhoto('sample.jpg');
  assert.equal(await readThumbnail('sample.jpg', 384), null);
  fs.mkdirSync(path.join(temporary, 'public/photos'), { recursive: true });
  fs.writeFileSync(path.join(temporary, 'public/photos/legacy.jpg'), red);
  assert.equal((await sharp(await readThumbnail('legacy.jpg', 768)).metadata()).width, 768);
  await writeFileKind('portrait', red, 'image/jpeg');
  assert.deepEqual((await readFileKind('portrait')).buf, red);
  const portrait = await readDisplayFile('portrait');
  assert.equal(portrait.mime, 'image/webp');
  assert.equal((await sharp(portrait.buf).metadata()).width, 768);
  await writeFileKind('portrait', blue, 'image/jpeg');
  assert.notDeepEqual((await readDisplayFile('portrait')).buf, portrait.buf);
  await deleteFileKind('portrait');
  assert.equal(await readDisplayFile('portrait'), null);
  await writeFileKind('icon-small', red, 'image/png');
  assert.equal((await sharp((await readDisplayFile('icon-small')).buf).metadata()).width, 32);
  console.log('PASS: upload variants, originals, cache hits, replacement, deletion, legacy thumbnails, portrait and icons');
})().finally(() => fs.rmSync(temporary, { recursive: true, force: true })).catch(error => { console.error(error); process.exitCode = 1; });
